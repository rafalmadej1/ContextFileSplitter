#!/usr/bin/env python3
"""
Splits .md files into business_logic/ and architecture/.

Structure:
  src/*.md            11 input files (sorted alphabetically -> F01..F11)
  work/NN.units.json  full segmentation (generated by `segment`)
  work/NN.to_tag.json input for Claude (generated by `segment`)
  work/NN.tags.json   unit classification (generated by the agent)
  business_logic/     business output (generated by `assemble`)
  architecture/       architecture output (generated by `assemble`)

Usage:
  python split_doc.py segment
  python split_doc.py assemble
  python split_doc.py check
"""
import json
import re
import sys
from pathlib import Path

SRC, WORK = Path("src"), Path("work")
BL_DIR, AR_DIR = Path("business_logic"), Path("architecture")

TECH = re.compile(
    r"\b(REST|GraphQL|endpoint\w*|HTTPS?|JSON|SQL|Kafka|Redis|API|gRPC|"
    r"microservice\w*|Docker|Kubernetes|POST|GET|PUT|DELETE|queue|schema|cache\w*)\b",
    re.I,
)
HEADING = re.compile(r"#{1,6} ")


def split_units(text):
    """Split markdown into blocks: each heading is a separate unit, code blocks are left intact.

    The text is split on blank lines (outside code blocks). Each heading
    becomes its own unit, and content enclosed in ``` fences is treated as
    a whole - blank lines inside it do not break the block.

    Args:
        text: Full contents of a markdown file.

    Returns:
        List of non-empty text units in the order they appear in the
        document.
    """
    units, buf, fence = [], [], False

    def flush():
        """Save the buffer contents as a new unit and clear the buffer.

        Does nothing if the buffer is empty.
        """
        if buf:
            units.append("\n".join(buf).strip("\n"))
            buf.clear()

    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            fence = not fence
        if not fence and not line.strip():
            flush()
            continue
        if not fence and HEADING.match(line):
            flush()
            units.append(line)
            continue
        buf.append(line)
    flush()
    return [u for u in units if u.strip()]


def sources():
    """Return a numbered list of input files from the src/ directory.

    The *.md files are sorted alphabetically and numbering starts at 1
    (matching the F01, F02, ... prefixes in unit identifiers). Exits with
    an error message if no files are found.

    Returns:
        List of (number, file path) pairs.
    """
    files = sorted(SRC.glob("*.md"))
    if not files:
        sys.exit("Brak plików w src/*.md")
    return list(enumerate(files, 1))


def load(path):
    """Load a UTF-8 encoded JSON file.

    Args:
        path: Path to the JSON file (a Path object).

    Returns:
        The deserialized file contents (usually a list of dicts).
    """
    return json.loads(path.read_text(encoding="utf-8"))


def segment():
    """Segment the files from src/ into units and write the results to work/.

    For each input file NN it creates:
        - work/NN.units.json  - the full list of units (headings and blocks)
        with identifiers in the FNN-UXXX format,
        - work/NN.to_tag.json - blocks only (no headings), together with the
        heading path (heading_path), intended for classification by the agent.

    Prints the number of units to be tagged for each file to standard output.
    """
    WORK.mkdir(exist_ok=True)
    for i, f in sources():
        units, path = [], []
        for n, text in enumerate(split_units(f.read_text(encoding="utf-8")), 1):
            uid = f"F{i:02d}-U{n:03d}"
            if HEADING.match(text):
                level = len(text) - len(text.lstrip("#"))
                path = path[: level - 1] + [text.lstrip("# ").strip()]
                units.append({"id": uid, "kind": "heading", "text": text})
            else:
                units.append(
                    {"id": uid, "kind": "block", "heading_path": " > ".join(path), "text": text}
                )
        (WORK / f"{i:02d}.units.json").write_text(
            json.dumps(units, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        to_tag = [
            {"id": u["id"], "heading_path": u["heading_path"], "text": u["text"]}
            for u in units
            if u["kind"] == "block"
        ]
        (WORK / f"{i:02d}.to_tag.json").write_text(
            json.dumps(to_tag, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"{f.name}: {len(to_tag)} jednostek do tagowania")


def assemble():
    """Assemble the output files in business_logic/ and architecture/ based on the tags.

    For each input file it loads work/NN.units.json and work/NN.tags.json
    (files without tags are skipped with a message) and builds two versions
    of the document:
        - headings go into both versions,
        - blocks tagged BL go only to business_logic/,
        - blocks tagged ARCH go only to architecture/,
        - MIXED blocks are split into bl_text and arch_text; each part goes to
        the corresponding directory together with a reference to the other,
        - untagged blocks go into both versions with an UNTAGGED annotation.

    Each unit is preceded by an HTML comment with its identifier, and each
    file by a comment with the path of the source file.
    """
    BL_DIR.mkdir(exist_ok=True)
    AR_DIR.mkdir(exist_ok=True)
    for i, f in sources():
        units = load(WORK / f"{i:02d}.units.json")
        tags_path = WORK / f"{i:02d}.tags.json"
        if not tags_path.exists():
            print(f"POMIJAM {f.name}: brak {tags_path}")
            continue
        tags = {t["id"]: t for t in load(tags_path)}
        bl, ar = [], []
        for u in units:
            uid, text = u["id"], u["text"]
            if u["kind"] == "heading":
                bl.append(text)
                ar.append(text)
                continue
            t = tags.get(uid)
            if t is None:
                msg = f"<!-- {uid} UNTAGGED -->\n{text}"
                bl.append(msg)
                ar.append(msg)
            elif t["tag"] == "BL":
                bl.append(f"<!-- {uid} -->\n{text}")
            elif t["tag"] == "ARCH":
                ar.append(f"<!-- {uid} -->\n{text}")
            else:  # MIXED
                if t.get("bl_text"):
                    bl.append(f"<!-- {uid} | see: architecture/{f.name} -->\n{t['bl_text']}")
                if t.get("arch_text"):
                    ar.append(f"<!-- {uid} | see: business_logic/{f.name} -->\n{t['arch_text']}")
        head = f"<!-- source: src/{f.name} -->\n\n"
        (BL_DIR / f.name).write_text(head + "\n\n".join(bl) + "\n", encoding="utf-8")
        (AR_DIR / f.name).write_text(head + "\n\n".join(ar) + "\n", encoding="utf-8")
        print(f"OK {f.name}")


def check():
    """Verify the consistency of the segmentation, tags and output files.

    For each input file it checks that:
        - a tags.json file exists,
        - every block has a tag (a missing tag counts as a problem),
        - every block is present in business_logic/ or architecture/,
        - the tags contain no identifiers outside the segmentation (surplus tags),
        - business_logic/ contains no technology names (the TECH pattern);
        HTML comments are ignored.

    Units with confidence below 0.7 are only reported for manual review and
    do not count as problems.

    Exits with code 1 if any problems were found, otherwise with code 0.
    """
    problems = 0
    low_conf = []
    for i, f in sources():
        units = load(WORK / f"{i:02d}.units.json")
        tags_path = WORK / f"{i:02d}.tags.json"
        if not tags_path.exists():
            print(f"[{f.name}] brak tags.json")
            problems += 1
            continue
        tags = {t["id"]: t for t in load(tags_path)}
        bl_text = (BL_DIR / f.name).read_text(encoding="utf-8") if (BL_DIR / f.name).exists() else ""
        ar_text = (AR_DIR / f.name).read_text(encoding="utf-8") if (AR_DIR / f.name).exists() else ""

        for u in units:
            if u["kind"] != "block":
                continue
            uid = u["id"]
            if uid not in tags:
                print(f"[{f.name}] BRAK TAGU: {uid}")
                problems += 1
            elif tags[uid].get("confidence", 1) < 0.7:
                low_conf.append(uid)
            if f"<!-- {uid} " not in bl_text and f"<!-- {uid} " not in ar_text:
                print(f"[{f.name}] NIEOBECNE W WYNIKU: {uid}")
                problems += 1

        extra = set(tags) - {u["id"] for u in units}
        for uid in sorted(extra):
            print(f"[{f.name}] NADMIAROWY TAG: {uid}")
            problems += 1

        # czystość: technologie w BL (poza komentarzami)
        for line in re.sub(r"<!--.*?-->", "", bl_text, flags=re.DOTALL).splitlines():
            m = TECH.search(line)
            if m:
                print(f"[BL {f.name}] technologia '{m.group(0)}': {line.strip()[:80]}")
                problems += 1

    if low_conf:
        print(f"\nNiska pewność (<0.7), do ręcznego przeglądu: {', '.join(low_conf)}")
    print(f"\nProblemów: {problems}")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    cmds = {"segment": segment, "assemble": assemble, "check": check}
    if len(sys.argv) != 2 or sys.argv[1] not in cmds:
        sys.exit(__doc__)
    cmds[sys.argv[1]]()