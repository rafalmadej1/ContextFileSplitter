#!/usr/bin/env python3
"""
Splits Markdown (.md) files into business_logic/ and architecture/.

Structure:
  src/*.md            source files (sorted alphabetically -> F01..FNN)
  work/NN.units.json  full segmentation (generated by `segment`)
  work/NN.to_tag.json input blocks for the agent (generated by `segment`)
  work/NN.tags.json   unit classifications (generated by the agent)
  business_logic/     business logic output (generated by `assemble`)
  architecture/       architecture output (generated by `assemble`)

Usage:
  python split_doc.py segment
  python split_doc.py assemble
  python split_doc.py check
"""
import json
import re
import sys
from pathlib import Path

SRC, WORK = Path("src"), Path("work")
BL_DIR, AR_DIR = Path("business_logic"), Path("architecture")

TECH_CS = re.compile(
    r"\b(REST|API|HTTPS?|JSON|SQL|gRPC|GET|POST|PUT|DELETE|PATCH)\b"
)
TECH_CI = re.compile(
    r"\b(GraphQL|endpoint\w*|Kafka|Redis|microservice\w*|Docker|Kubernetes|queue|schema|cache\w*)\b",
    re.I,
)
HEADING = re.compile(r"#{1,6} ")
FENCE_OPEN = re.compile(r"^\s*(`{3,}|~{3,})")
VALID_TAGS = {"BL", "ARCH", "MIXED"}


def find_tech(line):
    """Returns the first technical term match in a line (case-sensitive or case-insensitive)."""
    return TECH_CS.search(line) or TECH_CI.search(line)


def split_units(text):
    """Splits Markdown into blocks: each heading is a separate unit, code blocks remain intact."""
    units, buf, fence = [], [], None

    def flush():
        """Save the buffer contents as a new unit and clear the buffer.

        Does nothing if the buffer is empty.
        """
        if buf:
            units.append("\n".join(buf).strip("\n"))
            buf.clear()

    for line in text.splitlines():
        if fence is None:
            m = FENCE_OPEN.match(line)
            if m:
                fence = m.group(1)
                buf.append(line)
                continue
            if not line.strip():
                flush()
                continue
            if HEADING.match(line):
                flush()
                units.append(line)
                continue
            buf.append(line)
        else:
            buf.append(line)
            if re.match(rf"^\s*{fence[0]}{{{len(fence)},}}\s*$", line):
                fence = None
    flush()
    return [u for u in units if u.strip()]


def sources():
    """Return a numbered list of input files from the src/ directory.

    The *.md files are sorted alphabetically and numbering starts at 1
    (matching the F01, F02, ... prefixes in unit identifiers). Exits with
    an error message if no files are found.

    Returns:
        List of (number, file path) pairs.
    """
    files = sorted(SRC.glob("*.md"))
    if not files:
        sys.exit("No files found in src/*.md")
    return list(enumerate(files, 1))


def load(path):
    if not path.exists():
        sys.exit(f"Missing file: {path} (make sure 'segment' was run first)")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        sys.exit(f"Invalid JSON in {path}: {exc}")
    except OSError as exc:
        sys.exit(f"Cannot read {path}: {exc}")


def load_tags(path):
    data = load(path)
    if not isinstance(data, list):
        sys.exit(f"Invalid format in {path}: expected a JSON array")
    tags = {}
    for idx, item in enumerate(data):
        if not isinstance(item, dict) or "id" not in item or "tag" not in item:
            sys.exit(f"Invalid entry at index {idx} in {path}: missing 'id' or 'tag'")
        tags[item["id"]] = item
    return tags


def heading_level(text):
    return len(text) - len(text.lstrip("#"))


def segment():
    """Segment the files from src/ into units and write the results to work/.

    For each input file NN it creates:
        - work/NN.units.json  - the full list of units (headings and blocks)
        with identifiers in the FNN-UXXX format,
        - work/NN.to_tag.json - blocks only (no headings), together with the
        heading path (heading_path), intended for classification by the agent.

    Prints the number of units to be tagged for each file to standard output.
    """
    WORK.mkdir(exist_ok=True)
    for i, f in sources():
        units, path = [], []
        for n, text in enumerate(split_units(f.read_text(encoding="utf-8")), 1):
            uid = f"F{i:02d}-U{n:03d}"
            if HEADING.match(text):
                level = heading_level(text)
                title = re.sub(r"^#{1,6}\s+", "", text).strip()
                while path and path[-1][0] >= level:
                    path.pop()
                path.append((level, title))
                units.append({"id": uid, "kind": "heading", "text": text})
            else:
                heading_path = " > ".join(t for _, t in path)
                units.append(
                    {"id": uid, "kind": "block", "heading_path": heading_path, "text": text}
                )
        (WORK / f"{i:02d}.units.json").write_text(
            json.dumps(units, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        to_tag = [
            {"id": u["id"], "heading_path": u["heading_path"], "text": u["text"]}
            for u in units
            if u["kind"] == "block"
        ]
        (WORK / f"{i:02d}.to_tag.json").write_text(
            json.dumps(to_tag, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"{f.name}: {len(to_tag)} units to tag")


def assemble():
    """Assemble the output files in business_logic/ and architecture/ based on the tags.

    For each input file it loads work/NN.units.json and work/NN.tags.json
    (files without tags are skipped with a message) and builds two versions
    of the document:
        - headings go into both versions,
        - blocks tagged BL go only to business_logic/,
        - blocks tagged ARCH go only to architecture/,
        - MIXED blocks are split into bl_text and arch_text; each part goes to
        the corresponding directory together with a reference to the other,
        - untagged blocks go into both versions with an UNTAGGED annotation.

    Each unit is preceded by an HTML comment with its identifier, and each
    file by a comment with the path of the source file.
    """
    BL_DIR.mkdir(exist_ok=True)
    AR_DIR.mkdir(exist_ok=True)
    for i, f in sources():
        units = load(WORK / f"{i:02d}.units.json")
        tags_path = WORK / f"{i:02d}.tags.json"
        if not tags_path.exists():
            print(f"SKIP {f.name}: missing {tags_path}")
            continue
        tags = load_tags(tags_path)
        bl, ar = [], []
        pending_bl, pending_ar = [], []

        def emit_bl(block_text):
            for _, h_text in pending_bl:
                bl.append(h_text)
            pending_bl.clear()
            bl.append(block_text)

        def emit_ar(block_text):
            for _, h_text in pending_ar:
                ar.append(h_text)
            pending_ar.clear()
            ar.append(block_text)

        for u in units:
            uid, text = u["id"], u["text"]
            if u["kind"] == "heading":
                level = heading_level(text)
                while pending_bl and pending_bl[-1][0] >= level:
                    pending_bl.pop()
                pending_bl.append((level, text))
                while pending_ar and pending_ar[-1][0] >= level:
                    pending_ar.pop()
                pending_ar.append((level, text))
                continue
            t = tags.get(uid)
            if t is None:
                msg = f"<!-- {uid} UNTAGGED -->\n{text}"
                emit_bl(msg)
                emit_ar(msg)
            elif t["tag"] == "BL":
                emit_bl(f"<!-- {uid} -->\n{text}")
            elif t["tag"] == "ARCH":
                emit_ar(f"<!-- {uid} -->\n{text}")
            elif t["tag"] == "MIXED":
                if t.get("bl_text"):
                    emit_bl(f"<!-- {uid} | see: architecture/{f.name} -->\n{t['bl_text']}")
                if t.get("arch_text"):
                    emit_ar(f"<!-- {uid} | see: business_logic/{f.name} -->\n{t['arch_text']}")
            else:
                msg = f"<!-- {uid} INVALID_TAG:{t['tag']} -->\n{text}"
                emit_bl(msg)
                emit_ar(msg)
        head = f"<!-- source: src/{f.name} -->\n\n"
        (BL_DIR / f.name).write_text(head + "\n\n".join(bl) + "\n", encoding="utf-8")
        (AR_DIR / f.name).write_text(head + "\n\n".join(ar) + "\n", encoding="utf-8")
        print(f"OK {f.name}")


def check():
    """Verify the consistency of the segmentation, tags and output files.

    For each input file it checks that:
        - a tags.json file exists,
        - every block has a tag (a missing tag counts as a problem),
        - every block is present in business_logic/ or architecture/,
        - the tags contain no identifiers outside the segmentation (surplus tags),
        - business_logic/ contains no technology names (the TECH pattern);
        HTML comments are ignored.

    Units with confidence below 0.7 are only reported for manual review and
    do not count as problems.

    Exits with code 1 if any problems were found, otherwise with code 0.
    """
    problems = 0
    low_conf = []
    for i, f in sources():
        units_path = WORK / f"{i:02d}.units.json"
        if not units_path.exists():
            print(f"[{f.name}] missing {units_path}")
            problems += 1
            continue
        units = load(units_path)
        tags_path = WORK / f"{i:02d}.tags.json"
        if not tags_path.exists():
            print(f"[{f.name}] missing {tags_path}")
            problems += 1
            continue
        tags = load_tags(tags_path)
        bl_text = (BL_DIR / f.name).read_text(encoding="utf-8") if (BL_DIR / f.name).exists() else ""
        ar_text = (AR_DIR / f.name).read_text(encoding="utf-8") if (AR_DIR / f.name).exists() else ""

        for u in units:
            if u["kind"] != "block":
                continue
            uid = u["id"]
            if uid not in tags:
                print(f"[{f.name}] MISSING TAG: {uid}")
                problems += 1
                continue
            t = tags[uid]
            tag_val = t.get("tag")
            if tag_val not in VALID_TAGS:
                print(f"[{f.name}] INVALID TAG '{tag_val}': {uid}")
                problems += 1
            if t.get("confidence", 1) < 0.7:
                low_conf.append(uid)
            if tag_val == "MIXED":
                if f"<!-- {uid} " not in bl_text or f"<!-- {uid} " not in ar_text:
                    print(f"[{f.name}] INCOMPLETE MIXED OUTPUT: {uid}")
                    problems += 1
            elif f"<!-- {uid} " not in bl_text and f"<!-- {uid} " not in ar_text:
                print(f"[{f.name}] MISSING IN OUTPUT: {uid}")
                problems += 1

        extra = set(tags) - {u["id"] for u in units}
        for uid in sorted(extra):
            print(f"[{f.name}] EXTRA TAG: {uid}")
            problems += 1

        # Purity check: technology keywords in BL (outside HTML comments)
        for line in re.sub(r"<!--.*?-->", "", bl_text, flags=re.DOTALL).splitlines():
            m = find_tech(line)
            if m:
                print(f"[BL {f.name}] technology '{m.group(0)}': {line.strip()[:80]}")
                problems += 1

    if low_conf:
        print(f"\nLow confidence (<0.7), for manual review: {', '.join(low_conf)}")
    print(f"\nProblems: {problems}")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    cmds = {"segment": segment, "assemble": assemble, "check": check}
    if len(sys.argv) != 2 or sys.argv[1] not in cmds:
        sys.exit(__doc__)
    cmds[sys.argv[1]]()

